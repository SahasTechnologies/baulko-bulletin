/**
 * Generates src/lib/theme-morph.generated.ts — the sun and the moon as the theme
 * toggle can move between them.
 *
 * The icons themselves come from where every other icon here comes from:
 * `src/lib/icons.generated.ts`, which `scripts/sync-icons.mjs` fills from the
 * `ionicons` package. Nothing about the two shapes is written down by hand, and
 * nothing about them is shipped as markup either — what this produces is the
 * geometry a morph needs, which the browser cannot work out for itself:
 *
 *   - the sun's nine subpaths sorted into the eight rays and the disc, by area;
 *   - that disc and the moon each resampled to the same number of points, evenly
 *     spaced by arc length, so the two can be paired up point for point;
 *   - the moon rotated so its points start nearest the disc's, or the morph
 *     would carry a twist through it;
 *   - where each ray collapses to, which is the middle of its own box.
 *
 * It runs after `sync-icons.mjs`, reads only that file, and needs no network and
 * no package, so its `--check` is a plain comparison of what it would write
 * against what is committed — which is what `npm run check` and the deploy run.
 *
 *   node scripts/sync-theme-morph.mjs [--check]
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { alignRing, area, bounds, flatten, resample, subpaths } from "../src/lib/path-geometry.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ICONS = path.join(ROOT, "src", "lib", "icons.generated.ts");
const OUTPUT = path.join(ROOT, "src", "lib", "theme-morph.generated.ts");

/** The two icons, by the names `sync-icons.mjs` generates them under. */
const SUN = "sunny";
const MOON = "moon";

/**
 * Points per ring. Enough that the crescent's two tips come out sharp and the
 * circle's rim reads as round at any size it is drawn, and few enough that the
 * table stays a table rather than a payload.
 */
const STEPS = 96;

/* ----------------------------------------------------------------- reading */

/** The markup of one icon out of the generated set, without importing it. */
function iconMarkup(text, name) {
  const line = text.split("\n").find((candidate) => candidate.startsWith(`  ${JSON.stringify(name)}: `));
  if (!line) throw new Error(`${name} is not in src/lib/icons.generated.ts — run scripts/sync-icons.mjs first`);
  const value = line.slice(line.indexOf(":") + 1).trim().replace(/,$/, "");
  return JSON.parse(value);
}

function pathData(markup, name) {
  const d = markup.match(/\sd="([^"]+)"/)?.[1];
  if (!d) throw new Error(`${name} has no path to morph`);
  return d;
}

/* ---------------------------------------------------------------- deriving */

const icons = await readFile(ICONS, "utf8");
const sunMarkup = iconMarkup(icons, SUN);
const moonMarkup = iconMarkup(icons, MOON);

const view = Number(sunMarkup.match(/viewBox="0 0 (\d+) (\d+)"/)?.[1] ?? 0);
if (!view) throw new Error(`${SUN} has no square viewBox to work in`);

// The sun is one path holding the eight rays and the disc. Which is which is
// decided rather than assumed: the disc is the subpath enclosing by far the most
// area, and everything else is a ray.
const pieces = subpaths(pathData(sunMarkup, SUN)).map((piece) => {
  const ring = flatten(piece)[0];
  return { piece, ring, area: area(ring) };
});
if (pieces.length < 2) throw new Error(`${SUN} has only one subpath — is it the disc plus rays?`);

const disc = pieces.reduce((most, piece) => (piece.area > most.area ? piece : most));
const rays = pieces.filter((piece) => piece !== disc);

const sunRing = resample(disc.ring, STEPS).map(([x, y]) => [round(x), round(y)]);
const moonRing = alignRing(sunRing, resample(flatten(pathData(moonMarkup, MOON))[0], STEPS)).map(([x, y]) => [
  round(x),
  round(y),
]);

const rayData = rays.map(({ piece, ring }) => {
  const [minX, minY, maxX, maxY] = bounds(ring);
  return {
    d: piece.trim(),
    cx: round((minX + maxX) / 2),
    cy: round((minY + maxY) / 2),
  };
});

/** Two decimals: a hundredth of a unit in a 512 box, which is a tenth of a pixel. */
function round(value) {
  return Number(value.toFixed(2));
}

function flat(points) {
  return points.flatMap((point) => [round(point[0]), round(point[1])]);
}

/** A number array as lines of eight, which is as wide as anyone wants to read. */
function rows(numbers, indent = "  ") {
  const lines = [];
  for (let at = 0; at < numbers.length; at += 8) lines.push(`${indent}${numbers.slice(at, at + 8).join(", ")},`);
  return lines.join("\n");
}

const file =
  `/**\n` +
  ` * GENERATED by scripts/sync-theme-morph.mjs — do not edit by hand.\n` +
  ` *\n` +
  ` * The ${SUN} and ${MOON} icons from src/lib/icons.generated.ts, as two rings of\n` +
  ` * ${STEPS} points each — the same icon data every other icon on the site comes\n` +
  ` * from — plus where each of the sun's rays collapses to.\n` +
  ` *\n` +
  ` * That is all a morph needs and all the browser cannot work out for itself:\n` +
  ` * the two shapes paired point for point, so that easing one into the other is\n` +
  ` * a lerp rather than a library. Regenerate after the icons change:\n` +
  " * `npm run icons`.\n" +
  ` */\n\n` +
  `/** The icons' own square viewBox. */\n` +
  `export const VIEW = ${view};\n\n` +
  `/** How many points each ring is sampled to, said here so the two cannot drift. */\n` +
  `export const STEPS = ${STEPS};\n\n` +
  `/** The sun's disc: ${STEPS} points, x and y alternating from the icon's own origin. */\n` +
  `export const SUN: number[] = [\n${rows(flat(sunRing))}\n];\n\n` +
  `/** The moon, the same ${STEPS} points, rotated to start beside the disc's first. */\n` +
  `export const MOON: number[] = [\n${rows(flat(moonRing))}\n];\n\n` +
  `/**\n` +
  ` * The sun's rays, exactly as the icon draws them, each with the point its\n` +
  ` * collapse aims at: the middle of the ray's own box, so it shrinks away inside\n` +
  ` * itself instead of sliding somewhere.\n` +
  ` */\n` +
  `export const RAYS: { d: string; cx: number; cy: number }[] = [\n` +
  rayData
    .map(
      (ray) =>
        `  {\n    d: ${JSON.stringify(ray.d)},\n    cx: ${ray.cx},\n    cy: ${ray.cy},\n  },`
    )
    .join("\n") +
  `\n];\n`;

/* ----------------------------------------------------------------- writing */

if (process.argv.includes("--check")) {
  const committed = await readFile(OUTPUT, "utf8").catch(() => null);
  if (committed === file) {
    console.log(`[morph] ${SUN} → ${MOON} in step with src/lib/icons.generated.ts (${STEPS} points a ring)`);
    process.exit(0);
  }
  console.error("[morph] src/lib/theme-morph.generated.ts is out of date — run `npm run icons` and commit it.");
  if (committed) {
    const was = committed.length;
    console.error(`[morph] committed is ${was} bytes, this would write ${file.length}.`);
  }
  process.exit(1);
}

await writeFile(OUTPUT, file, "utf8");
console.log(
  `[morph] wrote ${path.relative(ROOT, OUTPUT)}: the disc is ${Math.round(area(disc.ring))} units² of ` +
    `${pieces.length} subpaths, and ${rays.length} rays collapse to their own middles.`
);
